// ========== 轨迹点（每车约 6-8 条，用于回放演示） ==========
function genTrack(vehicleId: string, baseLng: number, baseLat: number, baseTime: string): TrackPoint[] {
  const points: TrackPoint[] = []
  const base = new Date(baseTime).getTime()
  const locations = [
    `${baseLat.toFixed(4)},${baseLng.toFixed(4)} 附近`,
    '贵州省贵阳市花溪区青岩古镇',
    '贵州省贵阳市南明区甲秀楼',
    '贵州省黔南州荔波县小七孔景区',
    '贵州省安顺市黄果树瀑布景区',
  ]
  for (let i = 0; i < 6; i++) {
    const t = new Date(base + i * 10 * 60 * 1000) // 每 10 分钟一个点
    const pad = (n: number) => n.toString().padStart(2, '0')
    const ts = `${t.getFullYear()}-${pad(t.getMonth() + 1)}-${pad(t.getDate())} ${pad(t.getHours())}:${pad(t.getMinutes())}:${pad(t.getSeconds())}`
    points.push({
      trackId: `T-${vehicleId}-${i}`,
      vehicleId,
      timestamp: ts,
      lng: +(baseLng + i * 0.008).toFixed(6),
      lat: +(baseLat + i * 0.005).toFixed(6),
      speed: 30 + Math.floor(Math.random() * 50),
      heading: Math.floor(Math.random() * 360),
      location: locations[i % locations.length],
    })
  }
  return points
}

